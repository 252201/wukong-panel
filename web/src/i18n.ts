export function readLocalePreference(): Locale {
  try { return window.localStorage.getItem(LANGUAGE_STORAGE_KEY) === 'en-US' ? 'en-US' : 'zh-CN' }
  catch { return 'zh-CN' }
}

export function applyLocale(locale: Locale, persist = true) {
  document.documentElement.lang = locale
  if (!persist) return
  try { window.localStorage.setItem(LANGUAGE_STORAGE_KEY, locale) }
  catch { /* The active page can still use the selected locale. */ }
}

export function translateText(source: string, locale: Locale): string {
  if (locale === 'zh-CN') return source
  const leading = source.match(/^\s*/)?.[0] || ''
  const trailing = source.match(/\s*$/)?.[0] || ''
  const value = source.slice(leading.length, source.length - trailing.length)
  if (!value) return source
  if (Object.hasOwn(english, value)) return `${leading}${english[value]}${trailing}`
  if (!/[\u3400-\u9fff]/.test(value)) return source
  for (const [pattern, replace] of dynamicRules) {
    const match = value.match(pattern)
    if (match) return `${leading}${replace(...match)}${trailing}`
  }
  return source
}

type LocalizedValue = { source: string; rendered: string }
const textValues = new WeakMap<Text, LocalizedValue>()
const attributeValues = new WeakMap<Element, Map<string, LocalizedValue>>()
const localizedAttributes = ['aria-label', 'title', 'placeholder', 'alt', 'value']

function localizeTextNode(node: Text, locale: Locale) {
  const current = node.data
  const previous = textValues.get(node)
  const source = previous && current === previous.rendered ? previous.source : current
  const rendered = translateText(source, locale)
  textValues.set(node, { source, rendered })
  if (current !== rendered) node.data = rendered
}

function localizeAttributes(element: Element, locale: Locale) {
  let values = attributeValues.get(element)
  if (!values) { values = new Map(); attributeValues.set(element, values) }
  for (const name of localizedAttributes) {
    if (!element.hasAttribute(name)) continue
    const current = element.getAttribute(name) || ''
    const previous = values.get(name)
    const source = previous && current === previous.rendered ? previous.source : current
    const rendered = translateText(source, locale)
    values.set(name, { source, rendered })
    if (current !== rendered) element.setAttribute(name, rendered)
  }
}

function localizeSubtree(root: Node, locale: Locale) {
  if (root instanceof Text) { localizeTextNode(root, locale); return }
  if (!(root instanceof Element)) return
  localizeAttributes(root, locale)
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_ELEMENT | NodeFilter.SHOW_TEXT)
  let node: Node | null = walker.nextNode()
  while (node) {
    if (node instanceof Text) localizeTextNode(node, locale)
    else if (node instanceof Element) localizeAttributes(node, locale)
    node = walker.nextNode()
  }
}

export function createDocumentLocalizer(getLocale: () => Locale): () => void {
  const root = document.querySelector('#app')
  if (!root) return () => {}
  let frame = 0
  const refresh = () => {
    frame = 0
    localizeSubtree(root, getLocale())
  }
  const schedule = () => {
    if (!frame) frame = window.requestAnimationFrame(refresh)
  }
  localizeSubtree(root, getLocale())
  const observer = new MutationObserver(schedule)
  observer.observe(root, { childList: true, subtree: true, characterData: true, attributes: true, attributeFilter: localizedAttributes })
  return () => {
    observer.disconnect()
    if (frame) window.cancelAnimationFrame(frame)
  }
}

export function refreshDocumentLocale(locale: Locale) {
  const root = document.querySelector('#app')
  if (root) localizeSubtree(root, locale)
}
